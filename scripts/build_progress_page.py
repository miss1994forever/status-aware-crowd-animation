"""Generate the offline dashboard's data from project records; no dependencies."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCUMENTS = {
    "coordination": ("任务协调", "docs/任务协调.md"),
    "feedback": ("用户样片反馈", "docs/用户样片反馈.md"),
    "plan": ("两周实践计划", "docs/两周实践计划.md"),
    "engineering": ("动作预览验收", "docs/动作预览验收.md"),
    "research": ("status 数据审查", "docs/research/status数据审查.md"),
    "posture": ("源动作姿态核查", "docs/源动作姿态核查.md"),
    "locomotion": ("连续运动原型验收", "docs/连续运动原型验收.md"),
    "contactResearch": ("足部接触与脚滑证据", "docs/research/足部接触与脚滑证据.md"),
    "contactEngineering": ("足部接触改进验收", "docs/足部接触改进验收.md"),
    "encounter": ("双人相遇原型验收", "docs/双人相遇原型验收.md"),
    "candidates": ("多风格连续控制验收", "docs/多风格连续控制验收.md"),
    "predictive": ("预测式动作选择验收", "docs/预测式动作选择验收.md"),
    "mobility": ("多人通行改进验收", "docs/多人通行改进验收.md"),
}


def parse_tasks(markdown):
    section = markdown.split("| 工作项 |", 1)[1].split("###", 1)[0]
    tasks = []
    for line in section.splitlines():
        if not line.startswith("|") or "---" in line:
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 4:
            raise ValueError("Expected four task columns")
        title, status, evidence, owner = cells
        category = "pending" if "未实现" in status or "未完成" in status or "待开展" in status else "delivered" if "本阶段已交付" in status else "review"
        tasks.append(dict(id=hashlib.sha256(title.encode()).hexdigest()[:12], title=title,
                          status=status, evidence=evidence, owner=owner, category=category))
    if not tasks:
        raise ValueError("No progress tasks found")
    return tasks


def build():
    documents = {key: dict(title=title, path="../" + path,
                           text=(ROOT / path).read_text(encoding="utf-8"))
                 for key, (title, path) in DOCUMENTS.items()}
    source = documents["coordination"]["text"]
    checked = source.split("最后核对：", 1)[1].split("。", 1)[0]
    payload = dict(checked=checked, tasks=parse_tasks(source), documents=documents,
                   researchRoute=json.loads((ROOT / "data/research-route.json").read_text()))
    output = ROOT / "progress" / "data.js"
    output.parent.mkdir(exist_ok=True)
    output.write_text("// Generated by scripts/build_progress_page.py; edit source documents instead.\nwindow.PROJECT_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    return payload


if __name__ == "__main__":
    result = build()
    print(f"Updated progress/data.js: {len(result['tasks'])} tasks, {len(result['documents'])} documents")
